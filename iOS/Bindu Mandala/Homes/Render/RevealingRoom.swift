import Foundation

// MARK: - RING 6 · the ten Nigarbha Śaktis · the room where nothing arrives
//
// Design's `revealing(world, card, G)`, built on the Phase 3.1 spine. Its own
// header is the whole design:
//
//     RING 6 · REVEALING — it was already here.
//     Nothing arrives. A veil thins, and what was always in the room becomes
//     visible.
//
// and its deep sentence is the one line the walker is ever given for it:
// *"it was never hidden · you were the veil"*.
//
// The thread says the mechanism in one sentence, and every decision below is in
// it: *"Nothing arrives. **What is already in the room burns at full strength**
// and **a lit veil thins**."* Three claims — the content is at full strength
// from the first instant, the covering is **lit**, and the covering is the only
// thing that changes.
//
// **Nigarbha means *inside the womb*.** What this ring is about is not a gift
// and not an effect — it is a thing that has been here the whole time, under
// something. So the room's content is **already in the stone**, cut at its own
// depth before the walker arrives, and the only thing in the room with a clock
// is what lies over it.
//
// ─────────────────────────────────────────────────────────────────────────────
// WHAT MAKES THIS ROOM A NIGARBHA AND NOT ANY OTHER SISTER
// ─────────────────────────────────────────────────────────────────────────────
//
// Design's own question is *could this room belong to any other Śakti?* Two
// answers, one about the ring and one about the seat.
//
// **The ring, and it is a claim no other room in the hundred and two makes: the
// figure does not change.** Every other archetype's figure *does* something
// across the stay. The Siddhi's capacity is withdrawn, the Mātṛkā's letters are
// drawn into a column, the Karṣiṇī's two halves converge, the Mudrā's vaults
// open, the Anaṅga's eight effects grow out past the walker, the Sampradāya's
// gesture repeats outward, the Kulottīrṇa's gift arrives from beyond the wall.
// Here the ten are cut to their own depths at the first instant and **their
// depth and their light are the same two numbers at every moment of the stay**.
// Nothing about them is a function of `k` or of `b`. What has a clock is the
// **veil**, and the veil is the room's own material lying over them.
//
// That also makes this the one room whose light is *subtracted* rather than
// added as the stay deepens: the covering's light goes and nothing replaces it,
// and what is left is exactly what was burning at the first instant. Which is
// the sentence, in arithmetic — *it was never hidden*.
//
// **The seat.** Her tattva picks the physics the ten drift on, her position
// takes her turn of the ten, her bodily location decides which surface they are
// buried in and where in the frame the figure sits, her attribute acts inside
// it, and her gem lights it. Ten sisters, ten different burials.
//
// ─────────────────────────────────────────────────────────────────────────────
// THE VEIL, AND THE DEFECT THE DESIGN THREAD RECORDS AGAINST THIS RING
// ─────────────────────────────────────────────────────────────────────────────
//
// The thread's finding for Ring 6 is blunt — *"Ring 6's veil was unlit, so it
// extinguished rather than obscured. Now a lit surface."* A veil is not a
// blackout. It is the thing you are *actually looking at* — Design's is a
// `MeshStandardMaterial` at opacity 0.72 standing between the walker and the
// truth, lit from inside by the room's own key. **A veil must obscure something that is still there**, and
// something unlit obscures nothing; it deletes.
//
// So the veil here carries **more light than anything else in the room at the
// first instant**, and it is the room's own material: one **compaction**, laid
// across the whole figure. Three facts make that the right verb and the right
// shape, and none of them was chosen:
//
//   1. A compaction is *"driven down and densified, with almost no relief"*, and
//      it is the one profile in the five that is **flat-bottomed** — it goes
//      down once and stays down out to its reach. A veil has no form of its own.
//      And nothing here assigns it: ``RoomInscription/verb(for:previous:)`` reads
//      the verb from the part's own travel, and the veil does not travel. It is
//      the still skin the turning figure is under.
//   2. ``RoomMaterial/emission(at:)`` scales a mark's glow by how far it moved
//      the material **relative to its own depth**, so a mark with almost no
//      relief still emits at full strength. The veil is therefore able to be
//      *all light and no form*, which is what a scrim is, without anything in
//      the file asking for an exception.
//   3. And a broad lit field lying over relief **washes that relief out**. That
//      is not a hope — it is the defect this instrument has now found with a
//      picture three separate times: ``PressRoom``'s *"a lit area erases relief
//      rather than revealing it"*, ``CrossingRoom``'s seven converging discs that
//      made *"a pale structureless mass with every ring she had pressed lost
//      inside it"*, and Design's own first Laghimā defect. **In this one room
//      that is the premise rather than the bug.** The ten are under a lit field
//      that flattens them; the field goes; they were there the whole time.
//
// Design's own two numbers are spent in the two registers the instrument has,
// and they are the two halves of `max(0, 0.72 - k * 0.46 - b * 0.26)`:
//
//   * `k * 0.46` — the larger of the two, and it runs across the **first
//     adaptation**, before anything reverses. It is the veil in the material,
//     thinning while the eye settles. *You were the veil*: the walker's own
//     adaptation is what is clearing, which is why Design spends more of it on
//     `k` than on `b`.
//   * `b * 0.26` — the enclosure, giving way as the premise turns, through
//     ``HomeBecoming/archetype(_:)`` and ``RoomReversal``. It is already written
//     there as the revealing archetype's `yields`, so the grammar and this room
//     agree about the turn by construction rather than by two people typing the
//     same number.
//
// ─────────────────────────────────────────────────────────────────────────────
// AND WHAT DESIGN'S RISING EMISSIVE IS NOT SPENT ON
// ─────────────────────────────────────────────────────────────────────────────
//
// Design writes `m.material.emissiveIntensity = 3.2 + k * 1.4 + b * 2.2` on the
// ten. Carried literally, the truth would **brighten** as the veil clears — and
// then the room would be saying that something arrives, which is the one thing
// this archetype exists to deny. It is also double-counting: in Design's own
// scene the truth is *behind* a translucent shell, so what the eye receives is
// already the product of the two, and the shell is doing most of the work.
//
// Here there is no transmission — ``RoomMaterial/emission(at:)`` sums each
// action's own contribution and cannot attenuate one by another. So the rise is
// spent where Design's own sentence points: on **the veil's going**, which it
// already is. The truth's light is one number for the whole stay, and the
// contrast against the field around it climbs from a third again to everything,
// because the field is leaving. *It was never hidden.*
//
// ─────────────────────────────────────────────────────────────────────────────
// AND WHY THE TEN ARE BURIED AT TEN DIFFERENT DEPTHS
// ─────────────────────────────────────────────────────────────────────────────
//
// Design scatters them: `m.position.set(cos(a) * 6, y + sin(i * 1.7) * 2.6,
// sin(a) * 6 - 3)`. The ring is in the horizontal plane at her altitude and the
// `sin(i * 1.7) * 2.6` lifts each one to its own height — the axis that **leaves
// the plane**, which on the room's own material is the axis that runs *into the
// stone*.
//
// Read that way it stops being scatter and becomes the archetype: the ten are
// **buried at ten different depths**, the shallow ones almost at the surface and
// the deep ones far under it. A shallower one stands more proud of the stone, so
// it is the first to come back as the veil's light leaves; a deeper one is the
// last. Nothing schedules that and nothing is keyed to an index — the raking key
// finds relief in proportion to relief, and the ten have ten different reliefs.
//
// The burial is **static**, which matters twice: the verb classifier reads a
// velocity, so a mark's burial never reaches its verb, and the depth it sets is
// the same number at every instant of the stay.
struct RevealingRoom: RoomSurfaceMechanism {

    // MARK: - Who she is

    /// `khadgamalaPosition` 77–86. The only key.
    let position: Int
    /// Her physics, classified from her own tattva and quality.
    let physics: HomePhysics
    /// Her turn of the ten — Design's `(card.pos % 10) / 10`.
    let phase: Double

    init(_ reading: HomeGrammar.Reading) {
        self.position = reading.position
        self.physics = reading.physics
        self.phase = reading.phase ?? 0
    }

    /// The sixth āvaraṇa. Position decides who stands in it; nothing here
    /// consults a name.
    static let ring = 6

    // MARK: - Design's own numbers

    /// Ten. Design's `for (let i = 0; i < 10; i++)`, and the same ten her phase
    /// divisor counts (``HomeGrammar/phaseDivisor(for:)``).
    static let truths = 10

    /// The ring what is already here stands on: Design's `cos(a) * 6` /
    /// `sin(a) * 6`.
    static let truthRing: Double = 6

    /// How large one of them is: Design's `IcosahedronGeometry(1.4, 0)`, whose
    /// 1.4 is the radius — so it is already a reach rather than a span.
    static let truthSize: Double = 1.4

    /// How far the ten are scattered along the axis that leaves the plane, which
    /// is how deeply each is buried: Design's `sin(i * 1.7) * 2.6`.
    static let burialSpread: Double = 2.6
    static let burialTurn: Double = 1.7

    /// The veil's own radius: Design's `SphereGeometry(9.4, 36, 24)`. It stands
    /// outside the ring of six, which is Design saying in geometry that the veil
    /// covers the whole figure and a little more.
    static let veilRadius: Double = 9.4

    /// Design's displacement amplitude for the ten — `displace(kind, t, ph +
    /// i / 10, 0.8)`. The smallest of the six outer archetypes, because what is
    /// already here is not going anywhere.
    static let travel: Double = 0.8

    /// Design's veil, in one line: `veil.material.opacity = max(0, 0.72 -
    /// k * 0.46 - b * 0.26)`.
    ///
    /// ``veilYields`` is not used here — it is the enclosure's, through
    /// ``becoming``, and it is named beside its two siblings so the three can be
    /// read as Design's one expression rather than found in two files.
    static let veilOpacity: Double = 0.72
    static let veilThins: Double = 0.46
    static let veilYields: Double = 0.26

    /// **How much light one of the ten carries, at every instant of the stay.**
    ///
    /// One number, and its constancy is the room. It is the veil's own opening
    /// strength shared among the ten (``OuterRings/lightShare(of:)``, the root
    /// ``RoomInscription`` shares a rosary's beads by), so what the ten hold
    /// together at the end is what the covering held alone at the beginning —
    /// the same light in the room, differently distributed, and never more of it.
    static let truthGlow: Double = veilOpacity * OuterRings.lightShare(of: truths)

    /// Where the veil stands among the room's marks — last, as Design builds it
    /// last, and named so a check can ask for it without counting.
    static var veilIndex: Int { truths }

    // MARK: - How deeply one of the ten is buried

    /// `0` for the one lying just under the surface, `1` for the one furthest
    /// in — Design's `sin(i * 1.7)`, turned the right way up.
    ///
    /// The highest of Design's scattered positions is the least buried, so the
    /// sine is inverted: a thing that stands higher in her room stands nearer the
    /// top of the stone in this one.
    static func burial(_ index: Int) -> Double {
        (1 - sin(Double(index) * burialTurn)) / 2
    }

    /// How much relief one of the ten can give the surface it is under: the
    /// inverse of its burial, which is what ``OuterRings/depth(size:on:)`` reads.
    ///
    /// **Mapped across the whole span rather than clamped into it.** A fifth is
    /// the least the instrument lets a mark's size be — the floor
    /// ``OuterRings/mark(_:from:reach:size:travel:glow:material:)`` holds every
    /// other room's marks at — so the range is written as `0.2 … 1` and the ten
    /// burials are spread over all of it. Clamped instead, three of Design's ten
    /// would pile up on the floor together and the room would have seven depths
    /// in it rather than ten: `1 - sin(i · 1.7)` runs past a fifth at three of
    /// the ten, and a ring whose deepest three are indistinguishable has lost
    /// exactly the thing the burial is for.
    ///
    /// The fifth at the deep end is what keeps the deepest-buried of the ten
    /// **above the stone's own grain** rather than under it. A mark under the
    /// banding is not a faint mark — it is nothing, which is a different claim
    /// from the one this room is making.
    static let deepestRelief: Double = 0.2

    static func relief(_ index: Int) -> Double {
        deepestRelief + (1 - deepestRelief) * (1 - burial(index))
    }

    /// How far the burial carries one of the ten into the stone, in Design's own
    /// units: `sin(i * 1.7) * 2.6`, read as a depth rather than as a height.
    static func burialDepth(_ index: Int) -> Double {
        -burial(index) * burialSpread
    }

    // MARK: - The veil's own strength

    /// Design's `max(0, 0.72 - k * 0.46 - b * 0.26)`, without the enclosure's
    /// share — which is spent as a station rather than as light
    /// (``becoming``).
    ///
    /// It reaches nothing exactly where Design's expression does, because the
    /// two terms it keeps are the two Design's own veil loses first, and the
    /// third is the one the enclosure carries.
    func veilCover(settling k: Double, deep b: Double) -> Double {
        max(0, Self.veilOpacity - k * Self.veilThins - b * Self.veilYields)
    }

    // MARK: - What the premise becomes

    /// **It was never hidden · you were the veil.** Design's own deep sentence,
    /// and its two numbers: `veil.material.opacity = … - b * 0.26` — the veil
    /// that was around him clears — and `truth.scale.setScalar(1 + b * 0.5)` —
    /// what it hid was overhead the whole time.
    ///
    /// Read from ``HomeBecoming/archetype(_:)``, which is where the ten archetype
    /// reversals are, so this room and the grammar agree about the Nigarbha's
    /// turn by construction.
    ///
    /// **The growth is the room's, and not the ten's.** Design's `1 + b * 0.5`
    /// is a scale on the group the truth stands in, and this instrument has
    /// already paid once for reading a premise's number as an answer's — the
    /// Mātṛkā's letters against the Mātṛkā's column, which sent eight working
    /// faces three quarters of their clearance at the eye and rendered all eight
    /// rooms as one flat grey field. Here it is the canopy that takes the work
    /// over, and the ten are untouched by it, because *they were already here* is
    /// the one thing this room may not walk back.
    var becoming: HomeBecoming { .archetype(.revealing) }

    // MARK: - The figure, and the covering over it

    /// Where the ten stand, how large each of them is, and how far the veil has
    /// to reach to lie over all of them.
    ///
    /// Two adjustments to Design's ring, and both of them are floors rather than
    /// choices:
    ///
    ///   * **nothing is buried in the middle of the room.** The ten stand on a
    ///     ring and what is inside it is stone with nothing under it — so no
    ///     mark's stroke may run across the middle. A furrow holds its whole
    ///     depth for the length of its stroke and a crack is still at a quarter
    ///     of its own where it closes; both run
    ///     ``SurfaceAction/cutoffReaches`` of their reach *along* it, which is
    ///     ``OuterRings/clearance(ofReach:)``. The same floor also keeps the ten
    ///     from writing on one another, because ten marks on a ring of `4 r`
    ///     stand `2.47 r` apart. Design's own proportions already clear it on a
    ///     working face; it binds where the mesh cell has forced the marks up
    ///     (``OuterRings/narrowestMark``), which is what a floor or a canopy four
    ///     body-heights across does to a figure scaled into the picture.
    ///   * **the ten stand inside the veil's flat bottom.** Design's own veil is
    ///     a sphere of 9.4 around a ring of 6, so the ten sit well inside it; a
    ///     compaction is flat-bottomed but not infinitely so, and the same
    ///     proportion read literally on a small surface would leave the ten out
    ///     on the veil's falloff, lit by a third of it while the middle of the
    ///     room — where nothing is buried — carried all of it. So the veil opens
    ///     until the ring and one mark's reach are inside ``veilFlat``.
    ///
    /// The veil is allowed the whole of ``RoomReversal/answeringSpan`` rather
    /// than ``OuterRings/widestMark``, and that is the one place this room parts
    /// from the outer climb's own ceiling. The half is there because *a mark the
    /// premise makes is one of several*; the veil is not one of several. It is
    /// the single mark that is the whole surface, which is exactly the status the
    /// answering mark has, and half the span is still *"the widest a mark can be
    /// and still have material around it to be a mark in"*.
    func layout(figure: OuterRings.Figure, material: RoomMaterial)
        -> (reach: Double, ring: Double, veil: Double) {
        let reach = figure.reach(Self.truthSize)
        let ring = max(material.reach(worldUnits: figure.length(Self.truthRing)),
                       OuterRings.clearance(ofReach: reach))
        let veil = min(RoomReversal.answeringSpan,
                       max(OuterRings.narrowestMark,
                           max(material.reach(worldUnits: figure.length(Self.veilRadius)),
                               (ring + reach) / Self.veilFlat)))
        return (reach, ring, veil)
    }

    /// **How far out a compaction still carries three quarters of its own
    /// strength**, as a fraction of its reach — the part of the veil that is
    /// genuinely a flat lit field rather than its edge falling away.
    ///
    /// Solved off the profile rather than chosen: a compaction's relief is
    /// `1 - smooth(r)` (``SurfaceAction/relief(at:)``), so this is the `r` where
    /// `smooth(r)` is a quarter, found by bisection on Design's own smoothstep so
    /// that a change to the profile arrives here instead of being missed.
    static let veilFlat: Double = {
        var low = 0.0, high = 1.0
        for _ in 0..<60 {
            let mid = (low + high) / 2
            if RoomMaterial.smooth(mid) < 0.25 { low = mid } else { high = mid }
        }
        return (low + high) / 2
    }()

    // MARK: - What is done to the material

    func actions(at chamberTime: TimeInterval, stage: RoomStage) -> [RoomSurfaceKind: [SurfaceAction]] {
        let surface = stage.placement.surface
        guard let material = stage.materials[surface] else { return [:] }
        let k = stage.settling, b = stage.deep

        // The whole figure — the ten and the veil that covers them — brought into
        // the picture the walker is looking at.
        let figure = OuterRings.Figure(ring: Self.ring,
                                       spread: Self.truthRing * 2,
                                       part: Self.truthSize,
                                       on: material,
                                       bodyAltitude: stage.placement.bodyAltitude)
        let plan = layout(figure: figure, material: material)

        var marks: [SurfaceAction] = []
        marks.reserveCapacity(Self.truths + 1)

        // ── what is already here ────────────────────────────────────────────
        //
        // Ten marks, cut to ten different depths, at full strength from the
        // first instant. Their depth is their burial and their light is one
        // number, and neither of them is a function of the clock: this is the
        // one figure in the instrument that does not participate in its own
        // reversal.
        //
        // They **drift** — her physics, at her own turn of the ten — because a
        // room with no physics in it is a room that could be anyone's. What they
        // do not do is deepen, brighten, grow or leave.
        for index in 0..<Self.truths {
            let here = place(index: index, at: chamberTime,
                             figure: figure, stage: stage, material: material)
            let before = place(index: index, at: chamberTime - OuterRings.readOver,
                               figure: figure, stage: stage, material: material)
            marks.append(mark(here, from: before,
                              reach: plan.reach,
                              size: Self.relief(index),
                              glow: Self.truthGlow,
                              material: material))
        }

        // ── and the veil over them ──────────────────────────────────────────
        //
        // One mark, lying across the whole figure, carrying more light than
        // anything else in the room and almost no relief of its own — which is
        // what a scrim is, and which is why the ten under it cannot be read while
        // it is there. It does not travel, so the classifier reads it as a
        // compaction and nothing here has to say so.
        //
        // It is not removed and it is not withdrawn: its **light** goes, by
        // Design's own two terms, and when the light is gone the mark it was is a
        // shallow dish in the stone that the ten are lying in. Nigarbha.
        let veil = place(index: Self.veilIndex, at: chamberTime,
                         figure: figure, stage: stage, material: material)
        let veilBefore = place(index: Self.veilIndex, at: chamberTime - OuterRings.readOver,
                               figure: figure, stage: stage, material: material)
        marks.append(mark(veil, from: veilBefore,
                          reach: plan.veil,
                          size: 0,
                          glow: veilCover(settling: k, deep: b),
                          material: material))

        // …and the archetype's own reversal on top: the enclosure that was around
        // him giving way, and the canopy coming down to take the work over.
        var out = RoomReversal.actions(becoming, deep: b, stage: stage)
        out[surface, default: []].append(contentsOf: marks)
        return out
    }

    // MARK: - Where one part of the room's work stands

    /// Where one of the ten stands at one moment, or — at ``veilIndex`` — the
    /// veil that lies over all of them.
    ///
    /// Design's own placement is a ring in the **horizontal plane** at her
    /// altitude — `cos(a) * 6` in `x` and `sin(a) * 6` in `z` — with each of the
    /// ten lifted to its own height by `sin(i * 1.7) * 2.6`, and her physics on
    /// top of the whole thing.
    ///
    /// **The ring's plane is the surface**, which is ``BodilessRoom``'s own
    /// reading of Design's three axes and holds here for the same reason: a ring
    /// Design drew lying down has `x` and `z` running along the stone and `y`
    /// running into it. Taking ``RoomUnits/axes(of:)``' general rule — which is
    /// right for a figure drawn standing up — would put Design's burial *across*
    /// the ring on a working face, and the ten would be scattered sideways
    /// instead of buried.
    ///
    /// Which way *into* is, is still the instrument's: ``RoomUnits/SurfaceAxes``'
    /// own `outward`, so lying under a floor and lying above a ceiling are the
    /// same fact seen from two sides.
    ///
    /// The veil carries no angle, no burial and no displacement. It is the still
    /// skin, and its stillness is what the verb classifier reads.
    func place(index: Int, at chamberTime: TimeInterval,
               figure: OuterRings.Figure, stage: RoomStage,
               material: RoomMaterial) -> OuterRings.Place {
        let centre = stage.placement.coordinate
        guard index >= 0, index < Self.truths else {
            return OuterRings.Place(at: centre, into: 0)
        }

        let axes = RoomUnits.axes(of: material.surface)
        let ring = layout(figure: figure, material: material).ring
        let angle = Double(index) / Double(Self.truths) * 2 * .pi

        // Her physics, at this one's own turn of the ten — Design's `ph + i / 10`,
        // read against her own kernel's turn rather than typed
        // (``OuterRings/spread(index:of:kind:)``). For every kind that does not
        // fold this is Design's number exactly; for the kinds that do, a literal
        // `i / 10` would make the ring of ten move as five identical pairs.
        let drift = HomeGrammar.displace(
            physics,
            time: chamberTime,
            phase: phase + OuterRings.spread(index: index, of: Self.truths, kind: physics),
            amplitude: figure.length(Self.travel))

        let u = ring * cos(angle) + material.reach(worldUnits: drift.x)
        let v = ring * sin(angle) + material.reach(worldUnits: drift.z)
        return OuterRings.Place(at: SurfaceCoordinate(u: centre.u + u, v: centre.v + v).clamped,
                                into: (figure.length(Self.burialDepth(index)) + drift.y) * axes.outward)
    }

    /// One part of the room's work, as one action on the material.
    ///
    /// ``OuterRings/mark(_:from:reach:size:travel:glow:material:)`` is the outer
    /// climb's own, and this room cannot use it for one reason: it leans a mark's
    /// depth with how hard the part is bearing on the stone at that instant,
    /// which is right in five of the six outer archetypes and is the one thing
    /// this one may not do. **A depth that moved would make the ten a function of
    /// the clock**, and the whole claim of the room is that they are not.
    ///
    /// Everything else is unchanged and comes from the same places: the verb is
    /// ``RoomInscription/verb(for:previous:)``, read from this part's own travel
    /// over her own clock (``OuterRings/readOver``) and never assigned; the depth
    /// is ``OuterRings/depth(size:on:)``, floored at the stone's own grain and
    /// capped at one mark's worth; and the light is the surface's, which is to
    /// say it exists exactly as far as the material moved.
    func mark(_ here: OuterRings.Place, from before: OuterRings.Place,
              reach: Double, size: Double, glow: Double,
              material: RoomMaterial) -> SurfaceAction {
        let depth = OuterRings.depth(size: size, on: material)
        let now = OuterRings.motion(here, span: material.span)
        let then = OuterRings.motion(before, span: material.span)
        let where_ = here.at
        switch RoomInscription.verb(for: now, previous: then) {
        case .impression: return .impression(at: where_, reach: reach, depth: depth, glow: glow)
        case .furrow:     return .furrow(at: where_, reach: reach, depth: depth, glow: glow)
        case .crack:      return .crack(at: where_, reach: reach, depth: depth, glow: glow)
        case .swell:      return .swell(at: where_, reach: reach, depth: depth, glow: glow)
        case .compaction: return .compaction(at: where_, reach: reach, depth: depth, glow: glow)
        }
    }
}
